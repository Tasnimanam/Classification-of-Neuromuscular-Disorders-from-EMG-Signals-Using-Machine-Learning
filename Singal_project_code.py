# Load data and ensure all datasets have the same length
def load_and_trim_data(paths):
    data = [loadmat(path)['linear_envelope'].flatten() for path, _ in paths]
    min_length = min(len(d) for d in data)
    return [d[:min_length] for d in data], min_length

# Extract features from epoch data
def extract_features(epoch_data, fs):
    return [
        np.var(epoch_data), np.max(epoch_data), skew(epoch_data),
        kurtosis(epoch_data), np.sqrt(np.mean(epoch_data**2)),
        np.mean(np.abs(epoch_data)), np.trapz(epoch_data, dx=1/fs),
        np.sum(epoch_data > 0.002 * np.max(epoch_data))
    ]

