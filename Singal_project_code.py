# Train and evaluate model
def train_and_evaluate_model(model, model_name, X_train, Y_train, X_test, Y_test):
    model.fit(X_train, Y_train)
    Y_pred = model.predict(X_test)
    accuracy = accuracy_score(Y_test, Y_pred) * 100
    precision = precision_score(Y_test, Y_pred, average='weighted') * 100
    recall = recall_score(Y_test, Y_pred, average='weighted') * 100
    f1 = f1_score(Y_test, Y_pred, average='weighted') * 100
    kappa = cohen_kappa_score(Y_test, Y_pred) * 100
    mcc = matthews_corrcoef(Y_test, Y_pred) * 100
    conf_matrix = confusion_matrix(Y_test, Y_pred)

    print(f"{model_name} Confusion Matrix:\n{conf_matrix}")
    print(f"{model_name} Cohen’s Kappa: {kappa:.2f}%")
    print(f"{model_name} Matthews Correlation Coefficient (MCC): {mcc:.2f}%")

    # Binarize the output
    Y_test_bin = label_binarize(Y_test, classes=[0, 1, 2])
    Y_pred_bin = label_binarize(Y_pred, classes=[0, 1, 2])

    # Compute ROC curve and ROC area for each class
    fpr = dict()
    tpr = dict()
    roc_auc = dict()
    for i in range(3):
        fpr[i], tpr[i], _ = roc_curve(Y_test_bin[:, i], model.predict_proba(X_test)[:, i])
        roc_auc[i] = auc(fpr[i], tpr[i])

    # Plot ROC curve
    plt.figure()
    for i, disease in enumerate(['Healthy', 'Neuropathy', 'Myopathy']):
        plt.plot(fpr[i], tpr[i], lw=2, label=f'{disease} ROC curve (area = {roc_auc[i]:.2f})')
    plt.plot([0, 1], [0, 1], color='navy', lw=2, linestyle='--')
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title(f'{model_name} ROC Curve')
    plt.legend(loc="lower right")
    plt.show()

    # Compute precision-recall curve and area for each class
    precision_dict = dict()
    recall_dict = dict()
    pr_auc = dict()
    for i in range(3):
        precision_dict[i], recall_dict[i], _ = precision_recall_curve(Y_test_bin[:, i], model.predict_proba(X_test)[:, i])
        pr_auc[i] = auc(recall_dict[i], precision_dict[i])

    # Plot Precision-Recall curve
    plt.figure()
    for i, disease in enumerate(['Healthy', 'Neuropathy', 'Myopathy']):
        plt.plot(recall_dict[i], precision_dict[i], lw=2, label=f'{disease} Precision-Recall curve (area = {pr_auc[i]:.2f})')
        plt.xlabel('Recall')
        plt.ylabel('Precision')
        plt.title(f'{model_name} Precision-Recall Curve')
        plt.legend(loc="lower left")
        plt.show()

    # Cross-validation
    kfold = KFold(n_splits=5, shuffle=True, random_state=42)
    y_pred_cv = cross_val_predict(model, X_train, Y_train, cv=kfold)
    accuracy_cv = accuracy_score(Y_train, y_pred_cv) * 100
    print(f"Cross-Validation Accuracy ({model_name}): {accuracy_cv:.2f}%")

    return accuracy, precision, recall, f1, kappa, mcc

# Visualize extracted features
def visualize_features(X, Y, feature_names):
    fig, axes = plt.subplots(1, len(feature_names), figsize=(20, 5))
    colors = ['r', 'g', 'b']
    labels = ['Healthy', 'Neuropathy', 'Myopathy']
    for i, ax in enumerate(axes):
        for label, color in zip(np.unique(Y), colors):
            ax.scatter(np.arange(len(X[Y == label, i])), X[Y == label, i], c=color, label=labels[int(label)])
        ax.set_title(f'{feature_names[i]} Values')
        ax.set_xlabel('Sample Index')
        ax.set_ylabel(feature_names[i])
    plt.legend()
    plt.tight_layout()
    plt.show()

